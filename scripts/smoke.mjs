import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createReader,completed} from '../chain.js';
const deployment=JSON.parse(await fs.readFile('deployment.json','utf8'));
const reader=createReader();
const review=await reader.read(deployment.address,'get_review',['4']);
assert.equal(review.report.outcome,'MATCH');assert.deepEqual(review.deterministic_errors,[]);
const tx=await reader.transaction('0xaa2673ce72fcf879d5fe7de4a93bfdad2ba3721de5431515b38a9a730a50dcb6');
assert.equal(completed(tx),true);
console.log('Live frontend SDK smoke passed: finalized review #4 MATCH, zero hard-check violations, transaction finalized with a successful GenVM return.');
process.exit(0);
